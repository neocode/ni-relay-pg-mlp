"""Step 6 - deployment of the PG-MLP scheduler outside Python/scikit-learn.

* Exports the trained ensemble (models.pkl) to pgmlp_weights.json and to a self-contained C header
  pgmlp_scheduler.h (float32 weights; functions for the corrections x and the coefficients K, Eqs. (9)-(12)).
* Checks that a plain NumPy forward pass and the compiled C code reproduce the scikit-learn predictions
  (x12 and x13) on the 2500 test moves, 2000 random in-domain and 1000 out-of-domain inputs, and checks the
  status codes, the coefficients K against a Python reference, the fallback for inputs outside the tested
  range and for invalid inputs, and the guarantees K > 0, K13 <= K12^2/4
  (the C check is skipped if no C compiler is found).
* Measures the time of one prediction for scikit-learn, NumPy and C, and reports the memory footprint
  and the number of multiply-accumulate operations.

Output: pgmlp_weights.json, pgmlp_scheduler.h, deployment.txt.
Run after experiment.py and evaluation.py:  python deployment.py
"""
import json, os, pickle, shutil, subprocess, sys, tempfile, time
import numpy as np
from ni_drive import design_limits, ni_coefficients, B23, MMAX, WMAX, M3, UMAX
from experiment import rho, law
from results_io import load_results2

M = pickle.load(open('models.pkl', 'rb'))
nets, sp = M['m_pg'], M['sp']
lines = []
say = lambda *a: (lines.append(' '.join(str(x) for x in a)), print(*a))


def sk_predict(A, kh):
    """Reference: scikit-learn ensemble, Eq. (12) without the safeguard."""
    X = sp.transform(np.array([[np.log10(rho(A, kh)), kh]]))
    return law(A, kh) + np.mean([m.predict(X) for m in nets], axis=0)[0]


W = [[(c.astype(float), b.astype(float)) for c, b in zip(m.coefs_, m.intercepts_)] for m in nets]
MU, SD = sp.mean_.astype(float), sp.scale_.astype(float)


def np_predict(A, kh):
    """Plain NumPy forward pass (no scikit-learn)."""
    V, Am, J = design_limits(kh)
    r = A / (V * V / Am + V * Am / J)
    z = (np.array([np.log10(r), kh]) - MU) / SD
    y = np.zeros(2)
    for net in W:
        h = z
        for k, (c, b) in enumerate(net):
            h = h @ c + b
            if k < len(net) - 1:
                h = np.tanh(h)
        y += h
    return np.array([0.5 * np.log(min(r, 1.0)), 0.0]) + y / len(W)


# ---------- export ----------
json.dump(dict(scaler_mean=MU.tolist(), scaler_scale=SD.tolist(),
               networks=[[dict(W=c.tolist(), b=b.tolist()) for c, b in net] for net in W],
               activation='tanh', law='x12 = 0.5 ln min(rho, 1), x13 = 0',
               drive=dict(B23=B23, MMAX=MMAX, WMAX=WMAX, M3=M3, UMAX=UMAX)),
          open('pgmlp_weights.json', 'w'), indent=1)


def carr(name, a):
    a = np.asarray(a, dtype=np.float32).ravel()
    body = ', '.join(f'{v:.9g}f' for v in a)
    return f'static const float {name}[{a.size}] = {{{body}}};\n'


H = len(W[0][0][1])
hdr = ['/* PG-MLP scheduler of N-i switching coefficients (generated by deployment.py; do not edit).\n'
       ' *\n'
       ' * Contract\n'
       ' *   pgmlp_coefficients(A, kappa_hat, K) writes K = {K12, K13, K23} for a move of |A| rad, Eqs. (4)-(12),\n'
       ' *   and returns a status (bit flags, 0 = PGMLP_OK):\n'
       ' *     PGMLP_OK          |A| in [PGMLP_A_MIN, PGMLP_A_MAX] rad and kappa_hat in [PGMLP_K_MIN, PGMLP_K_MAX]\n'
       ' *                       (the training domain);\n'
       ' *     PGMLP_A_BELOW     |A| < PGMLP_A_MIN: extrapolated prediction; in the tests (3e-4 ... 3e-3 rad) the settling\n'
       ' *                       time degraded to tau1 <= 1.69, still far better than the analytic coefficients\n'
       ' *                       (tau1 up to 51) - extend the training range if such moves are commanded;\n'
       ' *     PGMLP_A_ABOVE     |A| > PGMLP_A_MAX: extrapolated prediction (tested up to 10 rad: tau1 <= 1.01, the\n'
       ' *                       gain of 1 ... 1.5 % over the law comes only with an overshoot of about 0.5 %);\n'
       ' *     PGMLP_K_OUTSIDE   kappa_hat outside [PGMLP_K_MIN, PGMLP_K_MAX]: extrapolated prediction (tested up to\n'
       ' *                       2.32, which occurs with the inertia margin kappa_hat / 0.9);\n'
       ' *     PGMLP_FALLBACK    input outside the tested range or invalid (non-finite, kappa_hat outside\n'
       ' *                       [PGMLP_K_HARD_MIN, PGMLP_K_HARD_MAX], |A| outside [PGMLP_A_HARD_MIN, PGMLP_A_HARD_MAX])\n'
       ' *                       or a non-finite intermediate result: the analytic coefficients (5), (6) are\n'
       ' *                       returned (for kappa_hat = 1 if kappa_hat itself is invalid). The hard limits are\n'
       ' *                       the range covered by the tests; widen them only after testing.\n'
       ' *   The sign of A is ignored (the drive is symmetric). Guarantees for every input: K12, K13, K23 finite and\n'
       ' *   positive, and K13 <= K12^2 / 4, i.e. real negative roots of the outer sliding equation (Eq. (12)).\n'
       ' *   Single-precision arithmetic only (float, logf, log10f, expf, tanhf); no dynamic memory; C99. */\n',
       '#ifndef PGMLP_SCHEDULER_H\n#define PGMLP_SCHEDULER_H\n#include <math.h>\n\n',
       f'#define PGMLP_NETS {len(W)}\n#define PGMLP_HIDDEN {H}\n',
       '#define PGMLP_A_MIN 0.003f\n#define PGMLP_A_MAX 3.0f\n#define PGMLP_K_MIN 0.5f\n#define PGMLP_K_MAX 2.0f\n',
       '#define PGMLP_A_HARD_MIN 3e-4f\n#define PGMLP_A_HARD_MAX 10.0f\n#define PGMLP_K_HARD_MIN 0.4f\n#define PGMLP_K_HARD_MAX 2.5f\n',
       'enum { PGMLP_OK = 0, PGMLP_A_BELOW = 1, PGMLP_A_ABOVE = 2, PGMLP_K_OUTSIDE = 4, PGMLP_FALLBACK = 8 };\n',
       f'static const float PGMLP_B23 = {B23!r}f, PGMLP_MMAX = {MMAX!r}f, PGMLP_WMAX = {WMAX!r}f;\n',
       f'static const float PGMLP_M3 = {M3!r}f, PGMLP_UMAX = {float(np.float32(UMAX))!r}f;\n',
       carr('PGMLP_MU', MU), carr('PGMLP_SD', SD)]
for n, net in enumerate(W):
    for k, (c, b) in enumerate(net):
        hdr.append(carr(f'PGMLP_W{n}_{k}', c.T))   # row-major [out][in]
        hdr.append(carr(f'PGMLP_B{n}_{k}', b))
hdr.append('static const float *PGMLP_W[PGMLP_NETS][3] = {' +
           ', '.join('{' + ', '.join(f'PGMLP_W{n}_{k}' for k in range(3)) + '}' for n in range(len(W))) + '};\n')
hdr.append('static const float *PGMLP_B[PGMLP_NETS][3] = {' +
           ', '.join('{' + ', '.join(f'PGMLP_B{n}_{k}' for k in range(3)) + '}' for n in range(len(W))) + '};\n\n')
hdr.append(r"""static inline void pgmlp_dense(const float *w, const float *b, const float *in, int n_in, float *out, int n_out, int act) {
    for (int o = 0; o < n_out; ++o) {
        float s = b[o];
        for (int i = 0; i < n_in; ++i) s += w[o * n_in + i] * in[i];
        out[o] = act ? tanhf(s) : s;
    }
}

/* dimensionless displacement rho, Eq. (7), for the limits (4) of kappa_hat */
static inline float pgmlp_rho(float A, float kappa_hat) {
    float b = PGMLP_B23 / kappa_hat, V = PGMLP_WMAX, Am = b * PGMLP_MMAX, J = b * PGMLP_M3 * PGMLP_UMAX;
    return A / (V * V / Am + V * Am / J);
}

/* corrections x = (x12, x13) of Eq. (12) without the safeguard; returns the status flags (see the contract) */
static inline int pgmlp_corrections(float A, float kappa_hat, float x[2]) {
    x[0] = 0.0f; x[1] = 0.0f;
    if (!isfinite(A) || !isfinite(kappa_hat) || kappa_hat < PGMLP_K_HARD_MIN || kappa_hat > PGMLP_K_HARD_MAX)
        return PGMLP_FALLBACK;
    A = fabsf(A);
    if (A < PGMLP_A_HARD_MIN || A > PGMLP_A_HARD_MAX) return PGMLP_FALLBACK;
    int status = (A < PGMLP_A_MIN ? PGMLP_A_BELOW : 0) | (A > PGMLP_A_MAX ? PGMLP_A_ABOVE : 0) |
                 (kappa_hat < PGMLP_K_MIN || kappa_hat > PGMLP_K_MAX ? PGMLP_K_OUTSIDE : 0);
    float r = pgmlp_rho(A, kappa_hat);
    float z[2] = {(log10f(r) - PGMLP_MU[0]) / PGMLP_SD[0], (kappa_hat - PGMLP_MU[1]) / PGMLP_SD[1]};
    float h1[PGMLP_HIDDEN], h2[PGMLP_HIDDEN], y[2], acc[2] = {0.0f, 0.0f};
    for (int n = 0; n < PGMLP_NETS; ++n) {
        pgmlp_dense(PGMLP_W[n][0], PGMLP_B[n][0], z, 2, h1, PGMLP_HIDDEN, 1);
        pgmlp_dense(PGMLP_W[n][1], PGMLP_B[n][1], h1, PGMLP_HIDDEN, h2, PGMLP_HIDDEN, 1);
        pgmlp_dense(PGMLP_W[n][2], PGMLP_B[n][2], h2, PGMLP_HIDDEN, y, 2, 0);
        acc[0] += y[0]; acc[1] += y[1];
    }
    x[0] = 0.5f * logf(r < 1.0f ? r : 1.0f) + acc[0] / PGMLP_NETS;
    x[1] = acc[1] / PGMLP_NETS;
    if (!isfinite(x[0]) || !isfinite(x[1])) { x[0] = 0.0f; x[1] = 0.0f; return PGMLP_FALLBACK; }
    return status;
}

/* analytic coefficients (5), (6) for kappa_hat */
static inline void pgmlp_analytic(float kappa_hat, float K[3]) {
    float b = PGMLP_B23 / kappa_hat, V = PGMLP_WMAX, Am = b * PGMLP_MMAX, J = b * PGMLP_M3 * PGMLP_UMAX;
    float vb = Am * Am / (2.0f * J), db = Am * Am * Am / (6.0f * J * J);
    K[2] = Am / (2.0f * J); K[0] = V / (2.0f * Am) + Am / (2.0f * J); K[1] = (K[0] * vb - db) / Am;
}

/* scheduled coefficients K = {K12, K13, K23}, Eqs. (5), (6), (9) and the safeguard of Eq. (12) */
static inline int pgmlp_coefficients(float A, float kappa_hat, float K[3]) {
    float x[2];
    int status = pgmlp_corrections(A, kappa_hat, x);
    if (!isfinite(kappa_hat) || kappa_hat < PGMLP_K_HARD_MIN || kappa_hat > PGMLP_K_HARD_MAX) kappa_hat = 1.0f;
    pgmlp_analytic(kappa_hat, K);
    float K12 = K[0] * expf(x[0]), K13 = K[1] * expf(x[1]);
    if (K13 > K12 * K12 / 4.0f) K13 = K12 * K12 / 4.0f;
    if (isfinite(K12) && isfinite(K13) && K12 > 0.0f && K13 > 0.0f) { K[0] = K12; K[1] = K13; }
    else status = PGMLP_FALLBACK;          /* keep the analytic coefficients */
    return status;
}
#endif
""")
open('pgmlp_scheduler.h', 'w').write(''.join(hdr))


A_HARD, K_HARD = (np.float32(3e-4), np.float32(10.0)), (np.float32(0.4), np.float32(2.5))   # as in the C header


def ref_coefficients(A, kh):
    """Python reference of pgmlp_coefficients: K = K0 exp(x) with the safeguard K13 <= K12^2/4, Eqs. (9), (12)."""
    st, x = ref_guarded(A, kh)
    if not (np.isfinite(kh) and K_HARD[0] <= kh <= K_HARD[1]):
        kh = 1.0
    K = ni_coefficients(*design_limits(kh))
    K12, K13 = K[0] * np.exp(x[0]), K[1] * np.exp(x[1])
    return st, np.array([K12, min(K13, K12 * K12 / 4.0), K[2]])


def ref_guarded(A, kh):
    """Python reference of the guarded C function: (status flags, x) based on the scikit-learn ensemble."""
    if not (np.isfinite(A) and np.isfinite(kh)) or not K_HARD[0] <= kh <= K_HARD[1]:
        return 8, np.zeros(2)
    A = abs(A)
    if not A_HARD[0] <= A <= A_HARD[1]:
        return 8, np.zeros(2)
    st = (1 if A < 0.003 else 0) | (2 if A > 3.0 else 0) | (4 if not 0.5 <= kh <= 2.0 else 0)
    return st, sk_predict(A, kh)


# ---------- accuracy of the exported implementations on the 2500 test moves ----------
R2 = load_results2()
cases = sorted({(r['A'], r['kappa']) for r in R2['rows'] if r['est'] == 'exact'})
ref = np.array([sk_predict(a, k) for a, k in cases])
npv = np.array([np_predict(a, k) for a, k in cases])
say(f'Test inputs: {len(cases)} moves')
say(f'NumPy vs scikit-learn: max |dx12| = {np.abs(npv - ref)[:, 0].max():.2e}, max |dx13| = {np.abs(npv - ref)[:, 1].max():.2e}')
nb = sum(c.size + b.size for net in W for c, b in net)
macs = sum(c.size for net in W for c, b in net)
say(f'Parameters: {nb} ({nb // len(W)} per network), float32 storage {4 * nb} bytes; '
    f'{macs} multiply-accumulate operations and {sum(len(b) for net in W for c, b in net[:-1])} tanh evaluations per prediction')


def timeit(f, n):
    f(*cases[0]); t0 = time.perf_counter()
    for i in range(n):
        f(*cases[i % len(cases)])
    return (time.perf_counter() - t0) / n


say(f'One prediction, scikit-learn ensemble: {1e6 * timeit(sk_predict, 2000):.0f} us')
say(f'One prediction, NumPy forward pass:    {1e6 * timeit(np_predict, 20000):.0f} us')

cc = shutil.which('gcc') or shutil.which('cc') or shutil.which('clang')
if cc is None:
    say('C check skipped: no C compiler found')
else:
    rng = np.random.default_rng(7)
    rnd = [(float(10 ** rng.uniform(np.log10(0.003), np.log10(3.0))), float(rng.uniform(0.5, 2.0))) for _ in range(2000)]
    ood = []
    while len(ood) < 1000:      # only inputs outside the training domain (but inside the hard limits)
        a_, k_ = float(10 ** rng.uniform(np.log10(3e-4), 1.0)), float(rng.uniform(0.4, 2.5))
        if not (0.003 <= a_ <= 3.0 and 0.5 <= k_ <= 2.0):
            ood.append((float(rng.choice([-1.0, 1.0])) * a_, k_))
    special = [(0.0, 1.0), (0.05, 0.0), (0.05, -1.0), (float('nan'), 1.0), (0.05, float('inf')), (-0.05, 1.3),
               (0.05, 1e-30), (0.05, 1e30), (1.4e-45, 1.0), (1e-8, 1.0), (1e3, 1.0), (float('-inf'), 1.0),
               (0.05, 0.04), (0.05, 25.0), (5e-4, 1.0), (8.0, 1.0), (12.0, 1.0), (0.05, 0.3), (0.05, 3.0)]
    fuzz = [(float(rng.choice([-1.0, 1.0]) * 10 ** rng.uniform(-45, 38)), float(rng.choice([-1.0, 1.0]) * 10 ** rng.uniform(-45, 38)))
            for _ in range(5000)]   # extreme values over the whole float range: only the guarantees are checked
    allc = cases + rnd + ood + special + fuzz
    tmp = tempfile.mkdtemp()
    with open(os.path.join(tmp, 'in.txt'), 'w') as f:
        for a_, k_ in allc:
            f.write(f'{a_!r} {k_!r}\n')
    src = os.path.join(tmp, 'test.c')
    open(src, 'w').write(r"""#include <stdio.h>
#include <stdlib.h>
#include <time.h>
#include "pgmlp_scheduler.h"
int main(int argc, char **argv) {
    (void)argc;
    static float A[16000], k[16000]; int n = 0; float x[2], K[3]; char sa[64], sk[64];
    FILE *f = fopen(argv[1], "r");
    while (n < 16000 && fscanf(f, "%63s %63s", sa, sk) == 2) { A[n] = strtof(sa, NULL); k[n] = strtof(sk, NULL); ++n; }
    fclose(f);
    FILE *g = fopen(argv[2], "w");
    for (int i = 0; i < n; ++i) {
        int st = pgmlp_corrections(A[i], k[i], x); int st2 = pgmlp_coefficients(A[i], k[i], K);
        fprintf(g, "%d %d %.9g %.9g %.9g %.9g %.9g\n", st, st2, x[0], x[1], K[0], K[1], K[2]);
    }
    fclose(g);
    volatile float sink = 0.0f; int reps = 200, m = atoi(argv[3]);
    clock_t t0 = clock();
    for (int r = 0; r < reps; ++r) for (int i = 0; i < m; ++i) { pgmlp_coefficients(A[i], k[i], K); sink += K[0]; }
    printf("%.3f\n", 1e6 * (double)(clock() - t0) / CLOCKS_PER_SEC / (reps * m));
    return 0;
}
""")
    exe = os.path.join(tmp, 'test.exe' if os.name == 'nt' else 'test')
    subprocess.run([cc, '-O2', '-std=c99', '-Wall', '-Wextra', '-I', os.getcwd(), src, '-o', exe, '-lm'], check=True)
    out = subprocess.run([exe, os.path.join(tmp, 'in.txt'), os.path.join(tmp, 'out.txt'), str(len(cases))],
                         check=True, capture_output=True, text=True).stdout.strip()
    cv = np.loadtxt(os.path.join(tmp, 'out.txt'))
    n1, n2, n3 = len(cases), len(cases) + len(rnd), len(cases) + len(rnd) + len(ood)
    refs = [ref_guarded(a_, k_) for a_, k_ in allc[:len(allc) - len(fuzz)]]
    rst = np.array([r[0] for r in refs]); rx = np.array([r[1] for r in refs])
    rK = np.array([ref_coefficients(a_, k_)[1] for a_, k_ in allc[:len(allc) - len(fuzz)]])
    for name, sl in (('2500 test moves', slice(0, n1)), ('2000 random in-domain inputs', slice(n1, n2)),
                     ('1000 out-of-domain inputs (extrapolated)', slice(n2, n3))):
        d = np.abs(cv[sl, 2:4] - rx[sl])
        dK = np.abs(cv[sl, 4:7] / rK[sl] - 1.0)
        say(f'C (float32) vs scikit-learn, {name}: max |dx12| = {d[:, 0].max():.2e}, max |dx13| = {d[:, 1].max():.2e}, '
            f'max relative |dK| = {dK.max():.2e}, status codes identical: {bool(np.all(cv[sl, 0] == rst[sl]))}')
    say('Status flags, out-of-domain inputs (1 A below, 2 A above, 4 kappa_hat outside, 8 fallback): ' +
        str({int(v): int(c) for v, c in zip(*np.unique(cv[n2:n3, 0], return_counts=True))}))
    say('Status flags identical to the Python reference for all special inputs: ' + str(bool(np.all(cv[n3:n3 + len(special), 0] == rst[n3:]))))
    say(f'Coefficients K of the special inputs vs the Python reference: max relative |dK| = '
        f'{np.nanmax(np.abs(cv[n3:n3 + len(special), 4:7] / rK[n3:] - 1.0)):.2e}')
    sp_ = cv[n3:n3 + len(special)]
    say('Special inputs (A, kappa_hat) -> status, K: ' + '; '.join(
        f'({a_}, {k_}) -> {int(r[1])}, K = ({r[4]:.4g}, {r[5]:.3g}, {r[6]:.3g})' for (a_, k_), r in zip(special, sp_)))
    Kall = cv[:, 4:7]
    say(f'All {len(allc)} calls (including {len(fuzz)} random inputs over the whole float range): K finite and positive: {bool(np.all(np.isfinite(Kall)) and np.all(Kall > 0))}; '
        f'K13 <= K12^2/4: {bool(np.all(Kall[:, 1] <= Kall[:, 0] ** 2 / 4 * (1 + 1e-6)))}')
    cpu = next((l.split(':', 1)[1].strip() for l in open('/proc/cpuinfo') if l.startswith('model name')), 'unknown CPU') \
        if os.path.exists('/proc/cpuinfo') else 'unknown CPU'
    say(f'One prediction (coefficients K), C -O2 on this computer ({cpu}): {out} us')
    shutil.rmtree(tmp, ignore_errors=True)
open('deployment.txt', 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
